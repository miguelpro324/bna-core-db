# Combines the per-version results of run_tests.sh into
#   pruebas/postgres/resultados.md           (full table, for the repository)
#   informe/pruebas-mysql.tex                (rows of the report table: MySQL failures)
#   informe/pruebas-objetos.tex              (rows of the report table: ported objects)
# Usage: combinar.py <out_dir> <resultados.md> <informe> <version>...
import csv
import os
import re
import sys

out_dir, md_path, model_dir, *versions = sys.argv[1:]

ORDER = {"L": 0, "M": 1, "C": 2, "F": 3, "R": 4}


def key(test_id):
    m = re.match(r"([A-Z])(\d+)(\w*)", test_id)
    return ORDER[m.group(1)], int(m.group(2)), m.group(3)


rows, results, full_version = {}, {}, {}
for v in versions:
    with open(os.path.join(out_dir, "version-pg%s.txt" % v)) as f:
        full_version[v] = f.read().strip()
    with open(os.path.join(out_dir, "resultado-pg%s.csv" % v), newline="", encoding="utf-8") as f:
        for tid, grupo, ref, desc, esperado, obtenido, res in csv.reader(f):
            rows.setdefault(tid, dict(grupo=grupo, ref=ref, desc=desc, esperado=esperado, obtenido={}))
            rows[tid]["obtenido"][v] = obtenido
            results[(tid, v)] = res

ids = sorted(rows, key=key)

# --- Markdown -------------------------------------------------------------
cols = ["PG %s" % full_version[v] for v in versions]
md = ["# Resultados de las pruebas de la base integrada", "",
      "Generado por `pruebas/postgres/run_tests.sh`. Las pruebas M reproducen en PostgreSQL las 25 fallas",
      "de la base unificada para MySQL; las F prueban los objetos portados e implementados;",
      "las R son las pruebas negativas originales del informe.", ""]
for v in versions:
    vals = [results[(t, v)] for t in ids]
    md.append("- PostgreSQL %s: %d pasan, %d fallan, %d N/A." % (
        full_version[v], vals.count("pasa"), vals.count("falla"), vals.count("N/A")))
md += ["", "| ID | Grupo | Referencia | Prueba | Esperado | Obtenido | %s |" % " | ".join(cols),
       "|---|---|---|---|---|---|%s|" % "|".join("---" for _ in versions)]


def cell(s):
    return s.replace("|", "\\|").replace("\n", " ")


for t in ids:
    r = rows[t]
    obt = list(dict.fromkeys(r["obtenido"].values()))
    obtained = obt[0] if len(obt) == 1 else " / ".join(
        "PG %s: %s" % (full_version[v], r["obtenido"][v]) for v in versions)
    md.append("| %s | %s | %s | %s | %s | %s | %s |" % (
        t, cell(r["grupo"]), cell(r["ref"]), cell(r["desc"]), cell(r["esperado"]), cell(obtained),
        " | ".join(results[(t, v)] for v in versions)))
with open(md_path, "w", encoding="utf-8") as f:
    f.write("\n".join(md) + "\n")

# --- LaTeX rows -------------------------------------------------------------
TEX = {"\\": r"\textbackslash{}", "_": r"\_", "%": r"\%", "&": r"\&", "#": r"\#",
       "$": r"\$", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def tex(s):
    s = "".join(TEX.get(c, c) for c in s)
    # identifiers (names with underscores or code-like tokens) in typewriter
    return re.sub(r"(?<![\w\\/.])([\w/.]*\w(?:\\_\w+)+(?:\.\w+)?(?:\(\))?)", r"\\nm{\1}", s)


def verdict(t):
    vals = {results[(t, v)] for v in versions}
    if vals == {"pasa"}:
        return "Pasa"
    if vals == {"N/A"}:
        return "N/A"
    return "Falla (%s)" % ", ".join("%s: %s" % (full_version[v], results[(t, v)]) for v in versions)


def write_rows(name, selected, with_reason):
    lines = ["% Generated by pruebas/postgres/run_tests.sh"]
    for t in selected:
        r = rows[t]
        desc = tex(r["desc"])
        if with_reason and results[(t, versions[0])] == "N/A":
            reason = re.sub(r"^N/A — ", "", r["obtenido"][versions[0]])
            desc += r" \newline\textit{%s}" % tex(reason[0].upper() + reason[1:])
        lines.append(r"%s & %s & %s & %s \\" % (t, tex(r["ref"]), desc, verdict(t)))
    with open(os.path.join(model_dir, name), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


write_rows("pruebas-mysql.tex", [t for t in ids if t[0] in "LMC"], True)
write_rows("pruebas-objetos.tex", [t for t in ids if t[0] in "FR"], False)

total = {v: [results[(t, v)] for t in ids] for v in versions}
with open(os.path.join(model_dir, "pruebas-stats.tex"), "w", encoding="utf-8") as f:
    f.write("% Generated by pruebas/postgres/run_tests.sh\n")
    vals = total[versions[0]]
    for k, n in (("pruebas", len(vals)), ("pruebaspasan", vals.count("pasa")),
                 ("pruebasfallan", vals.count("falla")), ("pruebasna", vals.count("N/A"))):
        f.write("\\expandafter\\def\\csname stat:%s\\endcsname{%d}\n" % (k, n))
    for v in versions:
        f.write("\\expandafter\\def\\csname stat:pgversion%s\\endcsname{%s}\n" % (v, full_version[v]))
print("Resultados en %s" % md_path)
